"""V3.7 evidence-first featured storyline ranking; never treats numerology as probability."""
import pandas as pd


def select_storyline_watch(combined, top_n=10):
    """Rank only supported flags, then pre-existing descriptive form as tiebreaker.

    Sourced flags are generated by V3.6 from player profiles and pre-slate logs.
    Unverified former-team, news and milestone labels are not counted.
    """
    frame = pd.DataFrame(combined).copy()
    if frame.empty:
        return frame, frame, None
    for field in ('Storyline count', 'Baseline Form Index', 'V3.2 Adjusted Index', 'Shots/G L5'):
        if field not in frame:
            frame[field] = 0
        frame[field] = pd.to_numeric(frame[field], errors='coerce').fillna(0)
    if 'Statistical rank' not in frame:
        frame['Statistical rank'] = range(1, len(frame) + 1)
    frame['Statistical rank'] = pd.to_numeric(frame['Statistical rank'], errors='coerce').fillna(len(frame) + 1)
    frame['Storyline tier'] = frame['Storyline count'].apply(lambda n: 'Verified-data storyline' if n > 0 else 'No supported storyline')
    eligible = frame[frame['Storyline count'] > 0].copy()
    eligible = eligible.sort_values(
        ['Storyline count', 'V3.2 Adjusted Index', 'Baseline Form Index', 'Player'],
        ascending=[False, False, False, True], kind='stable'
    )
    sleepers = eligible[(eligible['Statistical rank'] > 20) & (eligible['Shots/G L5'] >= 2)].head(top_n)
    top = eligible.head(top_n)
    featured = top.iloc[0] if not top.empty else None
    return top, sleepers, featured
